import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version',
};

const systemPrompt = `You are the OCF Compliance Agent — an AI assistant embedded in the Obligation Capsule Fabric platform. You help compliance officers:

1. **Monitor compliance status**: Review capsule health, risk scores, and evidence packets
2. **Auto-remediation**: When a check fails, suggest specific Azure/M365 policy fixes (exact policy IDs, Purview configs, Conditional Access rules)
3. **Risk scoring**: Explain how risk scores are calculated and what drives them higher
4. **Policy drift detection**: Identify when current cloud configurations diverge from capsule obligations
5. **Regulatory guidance**: Answer questions about GDPR, SOC2, HIPAA, PCI-DSS as they relate to Azure/M365

When suggesting remediations, be SPECIFIC:
- Name exact Azure Policy definition IDs
- Reference specific Purview sensitivity labels or DLP policies
- Cite Conditional Access policy conditions
- Provide PowerShell/CLI commands when helpful

Always maintain an authoritative but helpful tone. Flag critical non-compliance issues prominently.
Format responses with markdown for clarity.`;

serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get('LOVABLE_API_KEY');
    if (!LOVABLE_API_KEY) throw new Error('LOVABLE_API_KEY is not configured');

    const response = await fetch('https://ai.gateway.lovable.dev/v1/chat/completions', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model: 'google/gemini-3-flash-preview',
        messages: [
          { role: 'system', content: systemPrompt },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: 'Rate limit exceeded. Please try again shortly.' }), {
          status: 429, headers: { ...corsHeaders, 'Content-Type': 'application/json' },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: 'AI usage limit reached.' }), {
          status: 402, headers: { ...corsHeaders, 'Content-Type': 'application/json' },
        });
      }
      const text = await response.text();
      console.error('AI gateway error:', response.status, text);
      throw new Error(`AI gateway error: ${response.status}`);
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, 'Content-Type': 'text/event-stream' },
    });
  } catch (e) {
    console.error('compliance-chat error:', e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : 'Unknown error' }), {
      status: 500, headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    });
  }
});
